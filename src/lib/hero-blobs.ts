/**
 * Hero blob clusters, measured off the Figma hero frame (node 882:39).
 *
 * Each cluster is a photo clipped to a blob outline plus one decorative
 * shape. The photo is a plain rectangular JPEG clipped by an SVG path
 * instead of a pre-masked RGBA PNG, so the artwork stays vector-crisp and
 * every piece downloads on its own.
 *
 * All box values are percentages of the cluster box. `leftPct`/`topPct`
 * locate the element's CENTRE, because each one is rotated about its centre
 * and Figma measures the rotated bounding box.
 *
 * `clipPath` is in objectBoundingBox units (0-1), traced from the Figma
 * export's alpha channel and eroded slightly so the edge lands inside opaque
 * pixels. The rotation is applied on top, matching how Figma rotates the
 * vector and its image fill together.
 */
export interface HeroBlobBox {
  widthPct: number
  heightPct: number
  /** Centre X, as a percentage of the cluster box. */
  leftPct: number
  /** Centre Y, as a percentage of the cluster box. */
  topPct: number
  rotate: number
}

export interface HeroBlobCluster {
  id: string
  alt: string
  photo: string
  deco: string
  /** Cluster width / height, so the box keeps the Figma proportions. */
  aspect: number
  photoBox: HeroBlobBox
  decoBox: HeroBlobBox
  clipPath: string
}

